    try:
        from PIL import Image  # type: ignore

        base_img = Image.open(master_icon).convert("RGBA")
        bg = Image.new("RGBA", base_img.size, (13, 17, 24, 255))
        flat = Image.alpha_composite(bg, base_img).convert("RGB")
        for fname, _, _, px, _ in icon_specs:
            resized = flat.resize((px, px), Image.Resampling.LANCZOS)
            resized.save(appicon_dir / fname, format="PNG")
        used_backend = "Pillow"
    except Exception:
        used_backend = "sips"
        for fname, _, _, px, _ in icon_specs:
            subprocess.run(
                ["/usr/bin/sips", "-z", str(px), str(px), str(master_icon), "--out", str(appicon_dir / fname)],
                check=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )

    contents = {
        "images": [
            {
                "size": size_pt,
                "idiom": idiom,
                "filename": fname,
                "scale": scale,
            }
            for fname, size_pt, scale, _, idiom in icon_specs
        ],
        "info": {"version": 1, "author": "xcode"},
    }
    (appicon_dir / "Contents.json").write_text(
        json.dumps(contents, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Generated {len(icon_specs)} iOS AppIcons via {used_backend}")
